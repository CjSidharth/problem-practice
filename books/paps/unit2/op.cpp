#include <bits/stdc++.h>
using namespace std;
int main()
{
    int a = 0, b = 0;
    cin >> a >> b;
    cout << "Sum: " << (a + b) << "\n";
    cout << "Diff: " << (a - b) << "\n";
    cout << "Product: " << (a * b) << "\n";
    cout << "Quotient: " << (a / b) << "\n";
    cout << "Remainder: " << (a % b) << "\n";
}